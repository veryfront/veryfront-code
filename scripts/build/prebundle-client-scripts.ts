#!/usr/bin/env -S deno run --allow-all
/**
 * Pre-bundle Client Scripts for Compiled Binary
 *
 * In `deno compile` builds, framework source files (src/rendering/client/*)
 * aren't embedded in the binary. This script bundles the client-side router
 * and prefetch scripts ahead of time and writes them into templates.ts so
 * the existing import in client-runtime.ts picks them up automatically.
 *
 * Runs as part of `deno task build`, before `deno compile`.
 */

import { dirname, fromFileUrl, join } from "#std/path.ts";
import {
  EsbuildBundler,
  EsModuleLexer,
} from "../../extensions/ext-bundler-esbuild/src/index.ts";
import { register as registerContract } from "../../src/extensions/contracts.ts";
import {
  generateClientModule,
  generatePrefetchScript,
} from "../../src/build/production-build/client-runtime.ts";
import { CLIENT_STYLES } from "../../src/build/production-build/templates.ts";
import {
  collectFrameworkCandidates,
  renderFrameworkCandidatesModule,
} from "./framework-candidates.ts";

registerContract("Bundler", new EsbuildBundler());
registerContract("ModuleLexer", new EsModuleLexer());

const scriptDir = dirname(fromFileUrl(import.meta.url));
const projectRoot = join(scriptDir, "..", "..");
const templatesPath = join(
  projectRoot,
  "src",
  "build",
  "production-build",
  "templates.ts",
);
const candidatesPath = join(
  projectRoot,
  "src",
  "server",
  "handlers",
  "dev",
  "framework-candidates.generated.ts",
);

async function writeFormattedTypeScriptFile(
  path: string,
  contents: string,
): Promise<void> {
  await Deno.writeTextFile(path, contents);
  const result = await new Deno.Command("deno", {
    args: ["fmt", path],
    stdout: "null",
    stderr: "piped",
  }).output();
  if (!result.success) {
    const errorOutput = new TextDecoder().decode(result.stderr).trim();
    throw new Error(
      `Failed to format generated file ${path}${
        errorOutput ? `: ${errorOutput}` : ""
      }`,
    );
  }
}

console.log("[prebundle-client-scripts] Bundling client router...");
const routerBundle = await generateClientModule({ forceSourceBundle: true });

console.log("[prebundle-client-scripts] Bundling client prefetch...");
// deno-lint-ignore no-explicit-any
const prefetchBundle = await generatePrefetchScript(null as any, {
  forceSourceBundle: true,
});

const output = `/**
 * Embedded templates for production builds
 * These are embedded as strings to avoid file system dependencies in npm bundle
 *
 * AUTO-GENERATED by scripts/build/prebundle-client-scripts.ts
 * Do not edit manually — run \`deno task build\` to regenerate.
 * @module
 */

export const CLIENT_STYLES = ${JSON.stringify(CLIENT_STYLES)};

export const CLIENT_ROUTER_BUNDLE: string | undefined = ${
  JSON.stringify(routerBundle)
};

export const CLIENT_PREFETCH_BUNDLE: string | undefined = ${
  JSON.stringify(prefetchBundle)
};
`;

await writeFormattedTypeScriptFile(templatesPath, output);
console.log(`[prebundle-client-scripts] Written to ${templatesPath}`);

// --- Extract framework component Tailwind candidates ---
console.log(
  "[prebundle-client-scripts] Extracting framework component candidates...",
);

const sorted = await collectFrameworkCandidates(projectRoot);
const candidatesOutput = renderFrameworkCandidatesModule(sorted);

await writeFormattedTypeScriptFile(candidatesPath, candidatesOutput);
console.log(
  `[prebundle-client-scripts] Extracted ${sorted.length} framework candidates to ${candidatesPath}`,
);
