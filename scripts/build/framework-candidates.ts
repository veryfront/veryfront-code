import { extname, join } from "#std/path";
import { extractCandidates } from "../../src/html/styles-builder/candidate-tokenizer.ts";

export interface FrameworkCandidateIO {
  readonly readDir: (path: string) => AsyncIterable<Deno.DirEntry>;
  readonly readTextFile: (path: string) => Promise<string>;
}

export interface FrameworkCandidateArtifactIO extends FrameworkCandidateIO {
  readonly readFile: (path: string) => Promise<Uint8Array>;
}

export type FrameworkCandidateArtifactCheck =
  | {
    readonly status: "current";
    readonly candidateCount: number;
  }
  | {
    readonly status: "missing";
    readonly candidateCount: number;
  }
  | {
    readonly status: "stale";
    readonly candidateCount: number;
    readonly firstDifferenceOffset: number;
  };

const DEFAULT_IO: FrameworkCandidateIO = {
  readDir: Deno.readDir,
  readTextFile: Deno.readTextFile,
};
const DEFAULT_ARTIFACT_IO: FrameworkCandidateArtifactIO = {
  ...DEFAULT_IO,
  readFile: Deno.readFile,
};

const FRAMEWORK_SOURCE_DIRS = [
  ["src", "react", "components", "ui"],
  ["src", "react", "components", "chat"],
  ["src", "react", "primitives"],
] as const;
const SOURCE_EXTENSIONS = new Set([".ts", ".tsx"]);

function isTestFile(name: string): boolean {
  return /\.(test|spec)\.(ts|tsx)$/.test(name);
}

async function scanFrameworkDirectory(
  directory: string,
  candidates: Set<string>,
  io: FrameworkCandidateIO,
): Promise<void> {
  for await (const entry of io.readDir(directory)) {
    await scanFrameworkEntry(directory, entry, candidates, io);
  }
}

async function scanFrameworkEntry(
  directory: string,
  entry: Deno.DirEntry,
  candidates: Set<string>,
  io: FrameworkCandidateIO,
): Promise<void> {
  const path = join(directory, entry.name);
  if (entry.isDirectory) {
    await scanFrameworkDirectory(path, candidates, io);
    return;
  }
  if (
    !entry.isFile || !SOURCE_EXTENSIONS.has(extname(entry.name)) ||
    isTestFile(entry.name)
  ) {
    return;
  }

  const source = await io.readTextFile(path);
  for (const candidate of extractCandidates(source)) candidates.add(candidate);
}

async function scanOptionalFrameworkRoot(
  directory: string,
  candidates: Set<string>,
  io: FrameworkCandidateIO,
): Promise<void> {
  let iterator: AsyncIterator<Deno.DirEntry>;
  let entry: IteratorResult<Deno.DirEntry>;
  try {
    iterator = io.readDir(directory)[Symbol.asyncIterator]();
    entry = await iterator.next();
  } catch (error) {
    if (error instanceof Deno.errors.NotFound) return;
    throw error;
  }

  while (!entry.done) {
    await scanFrameworkEntry(directory, entry.value, candidates, io);
    entry = await iterator.next();
  }
}

/** Collect the deterministic CSS candidate set shipped by framework UI source. */
export async function collectFrameworkCandidates(
  projectRoot: string,
  io: FrameworkCandidateIO = DEFAULT_IO,
): Promise<readonly string[]> {
  const candidates = new Set<string>();
  for (const segments of FRAMEWORK_SOURCE_DIRS) {
    const directory = join(projectRoot, ...segments);
    await scanOptionalFrameworkRoot(directory, candidates, io);
  }
  return [...candidates].sort();
}

/** Render the tracked module in the same form used by the binary prebundle. */
export function renderFrameworkCandidatesModule(
  candidates: readonly string[],
): string {
  const sorted = [...new Set(candidates)].sort();
  return `/**
 * Auto-extracted Tailwind CSS candidates from framework components.
 *
 * AUTO-GENERATED by scripts/build/prebundle-client-scripts.ts
 * Do not edit manually — run \`deno task build\` to regenerate.
 * @module
 */

export const FRAMEWORK_CANDIDATES: readonly string[] = ${
    JSON.stringify(sorted, null, 2).replace(/\n\]$/, ",\n]")
  };
`;
}

function firstDifferentByte(
  expected: Uint8Array,
  actual: Uint8Array,
): number | undefined {
  const sharedLength = Math.min(expected.length, actual.length);
  for (let offset = 0; offset < sharedLength; offset += 1) {
    if (expected[offset] !== actual[offset]) return offset;
  }
  return expected.length === actual.length ? undefined : sharedLength;
}

/** Compare the tracked artifact with the canonical generated bytes. */
export async function checkFrameworkCandidateArtifact(
  projectRoot: string,
  artifactPath: string,
  io: FrameworkCandidateArtifactIO = DEFAULT_ARTIFACT_IO,
): Promise<FrameworkCandidateArtifactCheck> {
  const candidates = await collectFrameworkCandidates(projectRoot, io);
  const expected = new TextEncoder().encode(
    renderFrameworkCandidatesModule(candidates),
  );

  let actual: Uint8Array;
  try {
    actual = await io.readFile(artifactPath);
  } catch (error) {
    if (error instanceof Deno.errors.NotFound) {
      return { status: "missing", candidateCount: candidates.length };
    }
    throw error;
  }

  const firstDifferenceOffset = firstDifferentByte(expected, actual);
  if (firstDifferenceOffset === undefined) {
    return { status: "current", candidateCount: candidates.length };
  }
  return {
    status: "stale",
    candidateCount: candidates.length,
    firstDifferenceOffset,
  };
}
