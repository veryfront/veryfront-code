#!/usr/bin/env -S deno run -A
/**
 * Embeds cli/mcp/skills/* (SKILL.md and references/*.md) as
 * cli/skills/core-skills.generated.ts.
 *
 * The npm package and the compiled CLI do not carry cli/mcp/skills/, so the
 * skill loader falls back to this embedded copy there.
 * cli/skills/loader.test.ts fails when the copy drifts from the source files.
 */

import { fromFileUrl, join } from "#std/path";
import { loadSkill } from "../../cli/skills/loader.ts";
import type { LoadedSkill } from "../../cli/skills/types.ts";

const root = fromFileUrl(new URL("../../", import.meta.url));
const skillsDir = join(root, "cli/mcp/skills");
const outputPath = join(root, "cli/skills/core-skills.generated.ts");

const names: string[] = [];
for await (const entry of Deno.readDir(skillsDir)) {
  if (entry.isDirectory) names.push(entry.name);
}

const skills: LoadedSkill[] = [];
for (const name of names.sort()) {
  const skill = await loadSkill(join(skillsDir, name));
  if (!skill) throw new Error(`cli/mcp/skills/${name}/SKILL.md is missing or invalid`);
  skills.push({ ...skill, directory: `core:${name}` });
}

await Deno.writeTextFile(
  outputPath,
  `// Generated by scripts/build/generate-core-skills.ts from cli/mcp/skills. Do not edit.

import type { LoadedSkill } from "./types.ts";

export const CORE_SKILLS: LoadedSkill[] = ${JSON.stringify(skills, null, 2)};
`,
);

const fmt = await new Deno.Command(Deno.execPath(), {
  args: ["fmt", "--quiet", outputPath],
  cwd: root,
}).output();
if (!fmt.success) throw new Error("deno fmt failed on core-skills.generated.ts");

console.log(`Embedded ${skills.length} core skills in cli/skills/core-skills.generated.ts`);
