#!/usr/bin/env -S deno run --allow-all
/**
 * Pre-bundle the client hydration runtime.
 *
 * The runtime lives in src/html/hydration-script-builder/runtime/ as real typed
 * ES modules. The server hands the browser one JavaScript artifact, and both
 * the dev inline script and the production `/_veryfront/hydration-runtime.js`
 * module derive from the bundle written here — so the modules stay the single
 * source of truth while the callers keep their synchronous string APIs.
 *
 * React and the veryfront react runtime stay external: the document's import
 * map resolves those, and keeping them out is what lets a page load a
 * release-pinned router asset that predates `getNavigationStore`.
 *
 * Runs as part of `deno task generate`.
 */

import { dirname, fromFileUrl, join } from "#std/path.ts";
import * as esbuild from "npm:esbuild@0.28.1";

const scriptDir = dirname(fromFileUrl(import.meta.url));
const projectRoot = join(scriptDir, "..", "..");
const hydrationDir = join(projectRoot, "src", "html", "hydration-script-builder");
const entryPoint = join(hydrationDir, "runtime", "main.ts");
const outputPath = join(hydrationDir, "hydration-runtime.generated.ts");

/** Resolved by the browser's import map, never bundled. */
const EXTERNAL_SPECIFIERS = [
  "react",
  "react-dom",
  "react-dom/client",
  "veryfront/router",
  "veryfront/context",
];

const denoConfig = JSON.parse(await Deno.readTextFile(join(projectRoot, "deno.json")));
const importMap: Record<string, string> = denoConfig.imports ?? {};

function resolveImportMap(specifier: string): string | null {
  if (importMap[specifier]?.startsWith("./")) {
    return join(projectRoot, importMap[specifier] as string);
  }

  let bestKey = "";
  let bestTarget = "";
  for (const [key, value] of Object.entries(importMap)) {
    if (!key.endsWith("/") || !specifier.startsWith(key)) continue;
    if (key.length > bestKey.length) {
      bestKey = key;
      bestTarget = value;
    }
  }

  if (bestKey && bestTarget.startsWith("./")) {
    return join(projectRoot, bestTarget, specifier.slice(bestKey.length));
  }

  return null;
}

const denoImportMapPlugin: esbuild.Plugin = {
  name: "deno-import-map",
  setup(build) {
    build.onResolve({ filter: /^#/ }, (args) => {
      const resolved = resolveImportMap(args.path);
      if (resolved) return { path: resolved };
      throw new Error(`Hydration runtime imports an unresolvable specifier: ${args.path}`);
    });
  },
};

console.log("[prebundle-hydration-runtime] Bundling runtime/main.ts...");

const result = await esbuild.build({
  entryPoints: [entryPoint],
  bundle: true,
  write: false,
  format: "esm",
  platform: "browser",
  target: "es2020",
  // Left unminified so a production hydration failure still reads like the
  // source, which is what the hand-written script it replaces offered.
  minify: false,
  treeShaking: true,
  external: EXTERNAL_SPECIFIERS,
  plugins: [denoImportMapPlugin],
});

const bundle = result.outputFiles?.[0]?.text;
if (!bundle) {
  throw new Error("esbuild produced no output for the hydration runtime");
}

const output = `/**
 * Pre-bundled client hydration runtime.
 *
 * AUTO-GENERATED by scripts/build/prebundle-hydration-runtime.ts from
 * src/html/hydration-script-builder/runtime/. Do not edit manually — run
 * \`deno task generate\` to regenerate.
 * @module
 */

export const HYDRATION_RUNTIME_BUNDLE: string = ${JSON.stringify(bundle)};
`;

/** `deno fmt` decides the committed shape, so compare post-format both ways. */
async function formatTypeScript(source: string): Promise<string> {
  const formatted = await new Deno.Command("deno", {
    args: ["fmt", "-", "--ext", "ts"],
    stdin: "piped",
    stdout: "piped",
    stderr: "piped",
  }).spawn();

  const writer = formatted.stdin.getWriter();
  await writer.write(new TextEncoder().encode(source));
  await writer.close();

  const result = await formatted.output();
  if (!result.success) {
    const err = new TextDecoder().decode(result.stderr).trim();
    throw new Error(`Failed to format the generated bundle${err ? `: ${err}` : ""}`);
  }
  return new TextDecoder().decode(result.stdout);
}

const formattedOutput = await formatTypeScript(output);
await esbuild.stop();

// --check makes a stale committed bundle fail verify:quick instead of relying
// on someone noticing it missing from a PR diff.
if (Deno.args.includes("--check")) {
  const committed = await Deno.readTextFile(outputPath).catch(() => null);
  if (committed !== formattedOutput) {
    console.error(
      `[prebundle-hydration-runtime] ${outputPath} is stale.\n` +
        `  The committed bundle does not match src/html/hydration-script-builder/runtime/.\n` +
        `  Run \`deno task generate\` and commit the result.`,
    );
    Deno.exit(1);
  }
  console.log("[prebundle-hydration-runtime] Committed bundle is up to date");
} else {
  await Deno.writeTextFile(outputPath, formattedOutput);
  console.log(`[prebundle-hydration-runtime] Written to ${outputPath}`);
  console.log(`  hydration runtime: ${(bundle.length / 1024).toFixed(1)} KB`);
}
